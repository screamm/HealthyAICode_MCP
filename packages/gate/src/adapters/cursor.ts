/**
 * Adapter metadata that the gate conformance self-test and any cross-harness
 * orchestration layer can inspect to understand the capabilities of this adapter.
 */
export interface CursorAdapterMetadata {
  /** Canonical adapter identifier. */
  name: typeof ADAPTER_NAME;
  /**
   * Enforcement level relative to Claude Code's PreToolUse hard-deny.
   * "advisory" = the gate informs but cannot block; "enforced" = the gate
   * blocks before the edit lands.
   */
  enforcement: typeof ENFORCEMENT_LEVEL;
  /**
   * Which Cursor hook type the post-edit handler is wired to.
   * afterFileEdit is the only hook that fires on file writes; it is
   * informational only and cannot block or revert an edit.
   */
  hookType: 'afterFileEdit';
  /**
   * Explains why enforcement is advisory rather than enforced.
   * Included so tooling surfacing this metadata can be honest with operators.
   */
  limitationNote: string;
}

