/**
 * Returns the JSON object to merge into a project's `.cursor/hooks.json` to
 * wire the afterFileEdit handler to this adapter's runner script.
 *
 * @param runnerPath - Path to the Node runner script that invokes
 *   `handleAfterFileEditHook`. Example: `node .cursor/hooks/healthy-ai-code-gate.js`
 */
export function buildCursorHooksEntry(runnerPath: string): Record<string, unknown> {
  return {
    afterFileEdit: {
      command: runnerPath,
      timeout: 15000,
    },
  };
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

function readStdin(stdin: NodeJS.ReadableStream): Promise<string> {
  return new Promise((resolve, reject) => {
    let data = '';
    stdin.setEncoding('utf-8');
    stdin.on('data', (chunk: string) => { data += chunk; });
    stdin.on('end', () => resolve(data));
    stdin.on('error', reject);
  });
}
