export function getCursorAdapterMetadata(): CursorAdapterMetadata {
  return {
    name: ADAPTER_NAME,
    enforcement: ENFORCEMENT_LEVEL,
    hookType: 'afterFileEdit',
    limitationNote:
      'Cursor does not expose a pre-edit hook that can veto a file write before it lands on disk. ' +
      'The afterFileEdit hook is informational only (source: cursor.com/docs/hooks, 2026-06-01). ' +
      'The best available enforcement in Cursor is: (1) a rules file that instructs the agent to ' +
      'call the gate MCP tool before editing, and (2) a post-edit warning that prompts the agent ' +
      'to revert if the gate would have denied. Neither is equivalent to the hard deny that ' +
      "Claude Code's PreToolUse hook provides.",
  };
}

// ---------------------------------------------------------------------------
// Hook configuration helper
