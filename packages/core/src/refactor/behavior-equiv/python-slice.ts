function resolvePython(): string {
  const override = (process.env.HEALTHY_AI_PYTHON ?? '').trim();
  if (override) return override;
  return process.platform === 'win32' ? 'python' : 'python3';
}

/**
 * Build a self-contained Python module exporting `targetName` by slicing it out of `source`.
 * `sourceFile` is the on-disk path (needed to resolve relative imports); pass `null` if unknown
 * (relative imports then decline honestly). Returns `{ ok:false }` for un-isolatable targets —
 * NEVER a fabricated pass.
 */
export function slicePythonFunction(
  source: string,
  targetName: string,
  sourceFile: string | null,
): PySliceResult {
  // Fast path: no imports at all → already self-contained.
  if (!/(?:^|\n)\s*(?:import\s+\w|from\s+[.\w])/.test(source)) {
    return { ok: true, source, inlined: [] };
  }

  let dir: string | null = null;
  try {
    dir = mkdtempSync(join(tmpdir(), 'py-slice-'));
    const scriptFile = join(dir, 'slice.py');
    const jobFile = join(dir, 'job.json');
    writeFileSync(scriptFile, SLICE_SCRIPT, 'utf8');
    writeFileSync(
      jobFile,
      JSON.stringify({ sourceFile: sourceFile ?? '', source, target: targetName }),
      'utf8',
    );
    const stdout = execFileSync(resolvePython(), [scriptFile, jobFile], {
      encoding: 'utf8',
      timeout: 15_000,
      maxBuffer: 16 * 1024 * 1024,
      windowsHide: true,
    });
    const lastLine = stdout.trim().split(/\r?\n/).filter(Boolean).pop() ?? '';
    const parsed = JSON.parse(lastLine) as
      | { ok: true; source: string; inlined: string[] }
      | { ok: false; reason: string };
    if (parsed.ok) return { ok: true, source: parsed.source, inlined: parsed.inlined ?? [] };
    return { ok: false, reason: parsed.reason };
  } catch (e) {
    return { ok: false, reason: `slice extractor failed: ${(e as Error).message}` };
  } finally {
    if (dir) {
      try {
        rmSync(dir, { recursive: true, force: true });
      } catch {
        /* ignore cleanup errors */
      }
    }
  }
}
