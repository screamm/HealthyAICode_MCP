/**
 * python-slice.ts — function-slice extraction for Python behaviour-equivalence on REAL files.
 *
 * The Python differential engine (`python-equiv.ts`) loads a module with
 * `importlib.util.spec_from_file_location` and executes it. A real dependency-laden file —
 * e.g. `requests/utils.py` with `from .compat import urlparse`, `from urllib3.util import …`,
 * and module-level constants — fails to load (relative import with no parent package, or a
 * third-party dep absent in the sandbox). The engine then honestly degrades to `unverified`.
 *
 * This module bridges that gap by running an AST-based slice extractor (in Python, where the
 * semantics belong) that pulls the TARGET function PLUS the transitive closure of the
 * module-level names it actually references into one self-contained module. Imports are
 * handled per an HONEST rule set:
 *
 *   (a) module-level CONSTANTS / helper functions / classes the target uses → inlined.
 *   (b) `from .sibling import name` (relative) where `name` resolves in the sibling file to a
 *       stdlib re-export or a trivial binding (`builtin_str = str`)               → resolved &
 *       inlined / rewritten to the underlying stdlib import.                          inlined.
 *   (c) stdlib `import`/`from` the slice actually uses (re, struct, math, …)      → kept.
 *   (d) an import the slice uses that is THIRD-PARTY (urllib3, werkzeug, …) or a  → DECLINE with
 *       relative name that cannot be resolved to stdlib/constant                     a reason; the
 *                                                                                     caller emits
 *                                                                                     `unverified`.
 *
 * The purity gate in the engine still runs on the SLICE, so a target whose own body calls
 * `socket.inet_aton` / `os.environ` is correctly declined as impure (real network/IO), not
 * fabricated as a pass.
 *
 * Implementation: shells out to a generated, self-contained Python AST script (stdlib only),
 * mirroring the engine's subprocess design. Never throws — every failure becomes
 * `{ ok: false, reason }`.
 */

